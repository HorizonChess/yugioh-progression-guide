// Builds the collection prototype's data: three early sets from YGOPRODeck, a
// seeded "owned" share of each (with duplicates), and those cards' images from R2.
//   node prep.mjs      (writes data.js and img/, both gitignored except data.js)
import { mkdirSync, writeFileSync, existsSync, copyFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const DIR = dirname(fileURLToPath(import.meta.url));
const R2 = "https://pub-9397530dccf24d04a56c8eafb6e3edd0.r2.dev/cards";
const SETS = [
    ["LOB", "Legend of Blue Eyes White Dragon", "2002-03-08", 0.62],
    ["MRD", "Metal Raiders", "2002-06-26", 0.45],
    ["SRL", "Spell Ruler", "2002-09-16", 0.18],
];
mkdirSync(join(DIR, "img"), { recursive: true });

let seed = 7;
const rnd = () => ((seed = (seed * 16807) % 2147483647) / 2147483647);

const out = [];
for (const [code, name, date, share] of SETS) {
    const res = await fetch(`https://db.ygoprodeck.com/api/v7/cardinfo.php?cardset=${encodeURIComponent(name)}`);
    const { data } = await res.json();
    const cards = data.map((c) => {
        const print = c.card_sets.find((s) => s.set_code.startsWith(code + "-")) ?? c.card_sets[0];
        const common = print.set_rarity === "Common" || print.set_rarity.includes("Short Print");
        const owned = rnd() < share ? (common ? 1 + Math.floor(rnd() * 3) : 1) : 0;
        return {
            id: c.id, name: c.name, type: c.type, frameType: c.frameType, race: c.race, attribute: c.attribute ?? null,
            level: c.level ?? null, atk: c.atk ?? null, def: c.def ?? null, desc: c.desc,
            code: print.set_code, rarity: print.set_rarity, owned,
        };
    }).sort((a, b) => a.code.localeCompare(b.code));
    out.push({ code, name, date, cards });
    for (const c of cards.filter((c) => c.owned)) {
        const file = join(DIR, "img", `${c.id}.jpg`);
        if (existsSync(file)) continue;
        const r = await fetch(`${R2}/${c.id}_md.jpg`);
        if (r.ok) writeFileSync(file, Buffer.from(await r.arrayBuffer()));
    }
    console.log(code, cards.length, "cards,", cards.filter((c) => c.owned).length, "owned");
}
const back = join(DIR, "img", "back.jpg");
if (!existsSync(back)) writeFileSync(back, Buffer.from(await (await fetch(`${R2}/back_high.jpg`)).arrayBuffer()));
for (const f of ["LOB.webp", "MRD.webp", "SRL.webp", "wall-gemini-1.webp", "cartouche.webp", "yugi-neutral.webp"]) {
    const src = join(DIR, "../timeline-phone/img", f);
    if (existsSync(src)) copyFileSync(src, join(DIR, "img", f));
}
writeFileSync(join(DIR, "data.js"), `// Generated by prep.mjs\nconst SETS = ${JSON.stringify(out)};\n`);
